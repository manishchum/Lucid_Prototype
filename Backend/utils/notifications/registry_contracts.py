# Quick in-memory lookup indices
SYSTEM_VARIABLE_MAP: Dict[str, Dict[str, Any]] = {v["key"]: v for v in SYSTEM_VARIABLES}
SYSTEM_EVENT_PRESET_MAP: Dict[str, Dict[str, Any]] = {p["key"]: p for p in SYSTEM_EVENT_PRESETS}


def get_system_variables() -> List[Dict[str, Any]]:
    """Returns all standardized system variables sorted by namespace, then key."""
    return sorted(SYSTEM_VARIABLES, key=lambda x: (x.get("namespace", ""), x.get("key", "")))


def get_system_variable_samples() -> Dict[str, Any]:
    """Returns sample values for all system variables plus their short aliases."""
    sample_ctx: Dict[str, Any] = {}
    for v in SYSTEM_VARIABLES:
        sample_ctx[v["key"]] = v.get("sample_value") or ""
        short_key = v["key"].split(".")[-1]
        if short_key not in sample_ctx:
            sample_ctx[short_key] = v.get("sample_value") or ""
    return sample_ctx


def get_system_event_presets() -> List[Dict[str, Any]]:
    """Returns all system event presets sorted by category, then key."""
    return sorted(SYSTEM_EVENT_PRESETS, key=lambda x: (x.get("category", ""), x.get("key", "")))


def get_system_event_preset(event_key: str) -> Optional[Dict[str, Any]]:
    """Fetches a system event preset by key."""
    return SYSTEM_EVENT_PRESET_MAP.get(event_key.strip().upper())
