# Backend/core/agent_activity/event_manager.py
"""
Execution Event Manager for the Natural-Language Agent Activity System.
Manages monotonic event sequencing, parent-child spans, in-memory stream queues,
and async persistence to storage.
"""

import uuid
import asyncio
from typing import Dict, Any, List, Optional, AsyncGenerator
from .event_types import ExecutionStage, EventStatus, EventVisibility
from .event_schema import ExecutionEvent, NarrationEvent, FrontendActivityUpdate
from .execution_context import ExecutionContext, get_current_execution_context
from .event_storage import (
    record_execution_start,
    record_execution_finish,
    record_execution_event,
    record_narration_event,
)


class ExecutionEventManager:
    """
    Central event coordinator for an active agent query execution.
    Decoupled from agent implementation and model provider.
    """

    def __init__(
        self,
        context: ExecutionContext,
        query: str,
    ):
        self.context = context
        self.query = query
        self.events: List[ExecutionEvent] = []
        self.narration_events: List[NarrationEvent] = []
        self._stream_queue: asyncio.Queue[Optional[FrontendActivityUpdate]] = asyncio.Queue()
        self._is_completed = False

    @property
    def execution_id(self) -> str:
        return self.context.execution_id

    async def initialize(self) -> None:
        """Records initial execution start in persistent storage."""
        asyncio.create_task(
            record_execution_start(
                execution_id=self.context.execution_id,
                company_id=self.context.company_id,
                user_id=self.context.user_id,
                query=self.query,
                conversation_id=self.context.conversation_id,
                agent_type=self.context.agent_type,
                metadata=self.context.metadata,
            )
        )

    async def emit_execution_event(
        self,
        stage: ExecutionStage,
        event_type: str,
        source_component: str,
        payload: Optional[Dict[str, Any]] = None,
        status: EventStatus = EventStatus.COMPLETED,
        visibility: EventVisibility = EventVisibility.USER,
        duration_ms: Optional[int] = None,
    ) -> ExecutionEvent:
        """
        Records an execution event representing an actual operation or tool result.
        """
        event = ExecutionEvent(
            event_id=str(uuid.uuid4()),
            execution_id=self.context.execution_id,
            parent_event_id=self.context.get_active_span(),
            sequence=self.context.next_sequence(),
            stage=stage,
            event_type=event_type,
            status=status,
            visibility=visibility,
            source_component=source_component,
            payload=payload or {},
            duration_ms=duration_ms,
        )
        self.events.append(event)
        # Asynchronously persist to database in background
        asyncio.create_task(record_execution_event(event))
        return event

    async def emit_activity_update(
        self,
        stage: ExecutionStage,
        title: str,
        message: str,
        status: str = "completed",
        evidence: Optional[Dict[str, Any]] = None,
        duration_ms: Optional[int] = None,
    ) -> FrontendActivityUpdate:
        """
        Delivers an activity update to the frontend SSE stream queue.
        """
        update = FrontendActivityUpdate(
            execution_id=self.context.execution_id,
            sequence=self.context.current_sequence,
            stage=stage.value if hasattr(stage, "value") else str(stage),
            title=title,
            message=message,
            status=status,
            duration_ms=duration_ms,
            evidence=evidence,
        )
        await self._stream_queue.put(update)
        return update

    async def record_narration(
        self,
        title: str,
        message: str,
        stage: ExecutionStage,
        source_event_id: Optional[str] = None,
        provider: str = "gemini",
        model: Optional[str] = None,
        is_fallback: bool = False,
        duration_ms: Optional[int] = None,
    ) -> NarrationEvent:
        """
        Records the explanation generated by the Narrator Engine.
        """
        narr_event = NarrationEvent(
            id=str(uuid.uuid4()),
            execution_id=self.context.execution_id,
            source_event_id=source_event_id,
            title=title,
            message=message,
            stage=stage,
            provider=provider,
            model=model,
            is_fallback=is_fallback,
            duration_ms=duration_ms,
        )
        self.narration_events.append(narr_event)
        asyncio.create_task(record_narration_event(narr_event))
        return narr_event

    async def complete(self, status: str = "COMPLETED", metadata: Optional[Dict[str, Any]] = None) -> None:
        """Marks execution finished and signals end of activity stream."""
        if self._is_completed:
            return
        self._is_completed = True
        await self._stream_queue.put(None)  # Sentinel for stream consumers
        asyncio.create_task(
            record_execution_finish(
                execution_id=self.context.execution_id,
                status=status,
                metadata=metadata,
            )
        )

    async def stream_activity_updates(self) -> AsyncGenerator[FrontendActivityUpdate, None]:
        """Async generator yielding frontend activity updates as they are emitted."""
        while True:
            update = await self._stream_queue.get()
            if update is None:
                break
            yield update
