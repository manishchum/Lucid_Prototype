# Backend/core/agent_activity/event_schema.py
"""
Pydantic Schemas for Structured Agent Execution Events, Narrations, and Frontend Updates.
Follows versioned event contract (schema_version 1.0).
"""

from datetime import datetime, timezone
from typing import Dict, Any, Optional
from pydantic import BaseModel, Field
from .event_types import ExecutionStage, EventStatus, EventVisibility


class ExecutionEvent(BaseModel):
    """
    Ground truth telemetry emitted by agent components.
    Represents what actually happened during agent execution.
    """
    event_id: str
    execution_id: str
    parent_event_id: Optional[str] = None
    sequence: int
    schema_version: str = "1.0"
    stage: ExecutionStage
    event_type: str
    status: EventStatus = EventStatus.COMPLETED
    visibility: EventVisibility = EventVisibility.USER
    source_component: str
    payload: Dict[str, Any] = Field(default_factory=dict)
    duration_ms: Optional[int] = None
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class NarrationEvent(BaseModel):
    """
    Human-friendly explanation generated by the LLM Narrator (or fallback).
    Derived from verified ExecutionEvents.
    """
    id: str
    execution_id: str
    source_event_id: Optional[str] = None
    title: str
    message: str
    stage: ExecutionStage
    status: EventStatus = EventStatus.COMPLETED
    provider: str = "gemini"
    model: Optional[str] = None
    is_fallback: bool = False
    duration_ms: Optional[int] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class FrontendActivityUpdate(BaseModel):
    """
    Standardized payload delivered to frontend clients via SSE.
    Decoupled from underlying LLM narrator implementation.
    """
    event: str = "activity_update"
    execution_id: str
    sequence: int
    stage: str
    title: str
    message: str
    status: str = "completed"  # "running" | "completed" | "failed" | "retrying"
    duration_ms: Optional[int] = None
    evidence: Optional[Dict[str, Any]] = None
    timestamp: float = Field(default_factory=lambda: datetime.now(timezone.utc).timestamp())
